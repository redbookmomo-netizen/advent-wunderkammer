const NOTE_MAP = {
  C: 0, 'C#': 1, Db: 1, D: 2, 'D#': 3, Eb: 3, E: 4,
  F: 5, 'F#': 6, Gb: 6, G: 7, 'G#': 8, Ab: 8, A: 9, 'A#': 10, Bb: 10, B: 11
};

export function noteToMidi(token) {
  if (typeof token === 'number') return token;
  const m = /^([A-G](?:#|b)?)(-?\d+)$/.exec(token.trim());
  if (!m) return 60;
  return (parseInt(m[2], 10) + 1) * 12 + NOTE_MAP[m[1]];
}

// Helper to compile sequential voice tracks into sorted event list: { beat, midi, dur, vel, voice }
function compilePiece({ id, title, subtitle, composer, bpm, organMix = 0.22, voices }) {
  const events = [];
  let maxBeat = 0;

  voices.forEach((v, vIdx) => {
    let cursor = v.offset || 0;
    const baseVel = v.vel ?? (vIdx === 0 ? 0.92 : 0.56);
    const voiceType = v.type || (vIdx === 0 ? 'tine' : 'accomp');

    for (const item of v.notes) {
      const [pitch, dur, velScale = 1] = item;
      if (pitch !== null && pitch !== 'R') {
        const pitches = Array.isArray(pitch) ? pitch : [pitch];
        for (const p of pitches) {
          events.push({
            beat: cursor,
            midi: noteToMidi(p),
            dur: dur * 0.95,
            vel: Math.min(1, baseVel * velScale),
            voice: voiceType
          });
        }
      }
      cursor += dur;
    }
    if (cursor > maxBeat) maxBeat = cursor;
  });

  events.sort((a, b) => a.beat - b.beat || b.midi - a.midi);
  return { id, title, subtitle, composer, bpm, organMix, totalBeats: maxBeat, events };
}

